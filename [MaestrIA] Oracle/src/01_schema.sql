-- ============================================================
-- 1. DEPARTMENT
-- ============================================================

CREATE TABLE department (
    department_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    name          VARCHAR2(100) NOT NULL,
    location      VARCHAR2(100),

    CONSTRAINT pk_department
        PRIMARY KEY (department_id),

    CONSTRAINT uk_department_name
        UNIQUE (name)
);

-- ============================================================
-- 2. EMPLOYEE
-- ============================================================

CREATE TABLE employee (
    employee_id   NUMBER GENERATED BY DEFAULT AS IDENTITY,
    department_id NUMBER,
    manager_id    NUMBER,
    name          VARCHAR2(100) NOT NULL,
    email         VARCHAR2(150),
    job_title     VARCHAR2(100),
    salary        NUMBER(12,2),
    hire_date     DATE DEFAULT SYSDATE NOT NULL,
    status        VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,

    CONSTRAINT pk_employee
        PRIMARY KEY (employee_id),

    CONSTRAINT uk_employee_email
        UNIQUE (email),

    CONSTRAINT fk_employee_department
        FOREIGN KEY (department_id)
        REFERENCES department(department_id),

    CONSTRAINT fk_employee_manager
        FOREIGN KEY (manager_id)
        REFERENCES employee(employee_id),

    CONSTRAINT ck_employee_salary
        CHECK (salary >= 0),

    CONSTRAINT ck_employee_status
        CHECK (status IN ('ACTIVE', 'INACTIVE', 'ON_LEAVE'))
);

-- ============================================================
-- 3. CUSTOMER
-- ============================================================

CREATE TABLE customer (
    customer_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    name        VARCHAR2(150) NOT NULL,
    email       VARCHAR2(200),
    city        VARCHAR2(100),
    state       VARCHAR2(50),
    status      VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    created_at  TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT pk_customer
        PRIMARY KEY (customer_id),

    CONSTRAINT uk_customer_email
        UNIQUE (email),

    CONSTRAINT ck_customer_status
        CHECK (status IN ('ACTIVE', 'INACTIVE', 'BLOCKED'))
);

-- ============================================================
-- 4. ACCOUNT
-- ============================================================

CREATE TABLE account (
    account_id     NUMBER GENERATED BY DEFAULT AS IDENTITY,
    customer_id    NUMBER NOT NULL,
    account_number VARCHAR2(30) NOT NULL,
    account_type   VARCHAR2(20) NOT NULL,
    balance        NUMBER(15,2) DEFAULT 0 NOT NULL,
    status         VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    created_at     TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT pk_account
        PRIMARY KEY (account_id),

    CONSTRAINT uk_account_number
        UNIQUE (account_number),

    CONSTRAINT fk_account_customer
        FOREIGN KEY (customer_id)
        REFERENCES customer(customer_id),

    CONSTRAINT ck_account_type
        CHECK (account_type IN ('CHECKING', 'SAVINGS', 'INVESTMENT')),

    CONSTRAINT ck_account_status
        CHECK (status IN ('ACTIVE', 'BLOCKED', 'CLOSED'))
);

-- ============================================================
-- 5. ORDERS
-- ============================================================

CREATE TABLE orders (
    order_id      NUMBER GENERATED BY DEFAULT AS IDENTITY,
    customer_id   NUMBER NOT NULL,
    order_date    DATE DEFAULT SYSDATE NOT NULL,
    status        VARCHAR2(20) DEFAULT 'PENDING' NOT NULL,
    total_amount  NUMBER(15,2) DEFAULT 0 NOT NULL,

    CONSTRAINT pk_orders
        PRIMARY KEY (order_id),

    CONSTRAINT fk_orders_customer
        FOREIGN KEY (customer_id)
        REFERENCES customer(customer_id),

    CONSTRAINT ck_orders_status
        CHECK (
            status IN (
                'PENDING',
                'PROCESSING',
                'SHIPPED',
                'COMPLETED',
                'CANCELLED'
            )
        ),

    CONSTRAINT ck_orders_total
        CHECK (total_amount >= 0)
);

-- ============================================================
-- 6. ORDER_ITEM
-- ============================================================

CREATE TABLE order_item (
    order_item_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    order_id      NUMBER NOT NULL,
    product_name  VARCHAR2(150) NOT NULL,
    quantity      NUMBER NOT NULL,
    unit_price    NUMBER(12,2) NOT NULL,

    CONSTRAINT pk_order_item
        PRIMARY KEY (order_item_id),

    CONSTRAINT fk_order_item_order
        FOREIGN KEY (order_id)
        REFERENCES orders(order_id),

    CONSTRAINT ck_order_item_quantity
        CHECK (quantity > 0),

    CONSTRAINT ck_order_item_price
        CHECK (unit_price >= 0)
);

-- ============================================================
-- 7. TRANSACTION_STAGE
--
-- Intentionally has fewer constraints.
-- Later we will use this for:
--   - MERGE
--   - high-volume loading
--   - bad-data scenarios
--   - bulk processing
--   - staging-table exercises
-- ============================================================

CREATE TABLE transaction_stage (
    source_transaction_id NUMBER,
    account_id             NUMBER,
    transaction_type       VARCHAR2(20),
    amount                 NUMBER(15,2),
    transaction_date       TIMESTAMP,
    source_system          VARCHAR2(30),
    load_timestamp         TIMESTAMP DEFAULT SYSTIMESTAMP
);

-- ============================================================
-- 8. BANK_TRANSACTION
--
-- We avoid naming the table TRANSACTION because TRANSACTION
-- already has special meaning in SQL/Oracle terminology.
-- ============================================================

CREATE TABLE bank_transaction (
    transaction_id   NUMBER GENERATED BY DEFAULT AS IDENTITY,
    account_id       NUMBER NOT NULL,
    transaction_type VARCHAR2(20) NOT NULL,
    amount           NUMBER(15,2) NOT NULL,
    transaction_date TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    description      VARCHAR2(250),
    source_system    VARCHAR2(30),

    CONSTRAINT pk_bank_transaction
        PRIMARY KEY (transaction_id),

    CONSTRAINT fk_transaction_account
        FOREIGN KEY (account_id)
        REFERENCES account(account_id),

    CONSTRAINT ck_transaction_type
        CHECK (
            transaction_type IN (
                'CREDIT',
                'DEBIT',
                'TRANSFER',
                'PAYMENT',
                'REFUND'
            )
        ),

    CONSTRAINT ck_transaction_amount
        CHECK (amount > 0)
);

